#[cfg(not(feature = "test-support"))]
static BACKEND_API_BASE_URL: &str = "https://propelauth-api.com";
pub(crate) static AUTH_HOSTNAME_HEADER: &str = "X-Propelauth-url";

#[cfg(not(feature = "test-support"))]
fn backend_api_base_url() -> String {
    BACKEND_API_BASE_URL.to_string()
}

/// With the `test-support` feature, the URL set by `test_support::set_base_url`.
#[cfg(feature = "test-support")]
fn backend_api_base_url() -> String {
    crate::test_support::base_url_or_panic()
}

/// The main entrypoint of this library.
/// All authentication, authorization and API requests starts from this struct
#[derive(Debug, Clone)]
pub struct PropelAuth {
    config: Configuration,
    token_verification_metadata: AuthTokenVerificationMetadata,
    issuer: String,
}

impl PropelAuth {
    /// Initializes the PropelAuth library without making any external requests. This contrasts
    /// with `fetch_and_init` which will fetch the metadata needed to validate access tokens
    pub fn init(opts: AuthOptionsWithTokenVerification) -> Result<PropelAuth, InitializationError> {
        let auth_hostname = validate_auth_url_extract_hostname(&opts.auth_url)?;
        let issuer = "https://".to_string() + &auth_hostname;

        let configuration = Configuration {
            base_path: backend_api_base_url(),
            auth_hostname,
            bearer_access_token: Some(opts.api_key),
            ..Default::default()
        };

        Ok(PropelAuth {
            config: configuration,
            token_verification_metadata: opts.manual_token_verification_metadata,
            issuer,
        })
    }

    /// Initializes the PropelAuth library by making a single external request. This contrasts
    /// with `init` where you manually specify the metadata needed to validate access tokens
    pub async fn fetch_and_init(opts: AuthOptions) -> Result<PropelAuth, InitializationError> {
        let auth_hostname = validate_auth_url_extract_hostname(&opts.auth_url)?;
        let issuer = "https://".to_string() + &auth_hostname;

        let configuration = Configuration {
            base_path: backend_api_base_url(),
            auth_hostname,
            bearer_access_token: Some(opts.api_key),
            ..Default::default()
        };

        let token_verification_metadata = token_verification_metadata(&configuration)
            .await
            .map_err(|err| {
                map_autogenerated_error(
                    err,
                    InitializationError::UnexpectedException,
                    |status, _| match status.as_u16() {
                        401 => InitializationError::InvalidApiKey,
                        429 => InitializationError::PropelAuthRateLimit,
                        _ => InitializationError::UnexpectedException,
                    },
                )
            })?;

        Ok(PropelAuth {
            config: configuration,
            token_verification_metadata,
            issuer,
        })
    }

    /// API requests related to users
    pub fn user(&self) -> UserService<'_> {
        UserService {
            config: &self.config,
        }
    }

    /// API requests related to organizations
    pub fn org(&self) -> OrgService<'_> {
        OrgService {
            config: &self.config,
        }
    }

    /// API requests related to organizations
    pub fn api_key(&self) -> ApiKeyService<'_> {
        ApiKeyService {
            config: &self.config,
        }
    }

    /// Verify access tokens from your frontend
    pub fn verify(&self) -> TokenService<'_> {
        TokenService {
            token_verification_metadata: &self.token_verification_metadata,
            issuer: &self.issuer,
        }
    }

    /// API requests related to access tokens.
    pub fn access_token(&self) -> AccessTokenService<'_> {
        AccessTokenService {
            config: &self.config,
        }
    }

    /// API requests related to employees.
    pub fn employee(&self) -> EmployeeService {
        EmployeeService {
            config: &self.config,
        }
    }

    /// API requests related to mfa.
    pub fn mfa(&self) -> MfaService {
        MfaService {
            config: &self.config,
        }
    }
    
    /// API requests related to scim.
    pub fn scim(&self) -> ScimService {
        ScimService {
            config: &self.config,
        }
    }

    /// API requests related to user insights data.
    pub fn user_insights(&self) -> UserInsightsService {
        UserInsightsService {
            config: &self.config,
        }
    }
}

fn validate_auth_url_extract_hostname(auth_url: &str) -> Result<String, InitializationError> {
    Ok(Url::parse(auth_url)
        .map_err(|_| InitializationError::InvalidAuthUrl)?
        .host_str()
        .ok_or(InitializationError::InvalidAuthUrl)?
        .to_string())
}

#[cfg(test)]
mod tests {
    use crate::propelauth::auth::validate_auth_url_extract_hostname;
    use crate::propelauth::errors::InitializationError;

    #[test]
    fn bad_auth_url_is_rejected() {
        assert_eq!(
            Some(InitializationError::InvalidAuthUrl),
            validate_auth_url_extract_hostname("not.a.url").err()
        );
        assert_eq!(
            Some(InitializationError::InvalidAuthUrl),
            validate_auth_url_extract_hostname("fake").err()
        );
    }

    #[test]
    fn test_extract_hostname() {
        assert_eq!(
            Some("blah.com".to_string()),
            validate_auth_url_extract_hostname("https://blah.com").ok()
        );

        assert!(validate_auth_url_extract_hostname("blah").is_err());

        assert_eq!(
            Some("app.blah.co.uk".to_string()),
            validate_auth_url_extract_hostname("https://app.blah.co.uk/more").ok()
        );
    }
}

#[cfg(all(test, feature = "test-support"))]
mod test_support_tests {
    use super::PropelAuth;
    use crate::models::AuthTokenVerificationMetadata;
    use crate::propelauth::errors::InitializationError;
    use crate::propelauth::options::{AuthOptions, AuthOptionsWithTokenVerification};
    use crate::test_support::{clear_base_url, set_base_url, test_lock};
    use std::io::{Read, Write};
    use std::net::TcpListener;
    use std::sync::mpsc;
    use std::thread;
    use std::time::Duration;

    const AUTH_URL: &str = "https://auth.example.com";

    fn init_options() -> AuthOptionsWithTokenVerification {
        AuthOptionsWithTokenVerification {
            auth_url: AUTH_URL.to_string(),
            api_key: "api-key".to_string(),
            manual_token_verification_metadata: AuthTokenVerificationMetadata::default(),
        }
    }

    #[test]
    fn init_uses_the_override() {
        let _lock = test_lock();
        set_base_url("http://127.0.0.1:9");
        let auth = PropelAuth::init(init_options()).unwrap();
        clear_base_url();
        assert_eq!(auth.config.base_path, "http://127.0.0.1:9");
    }

    #[test]
    #[should_panic(expected = "must call propelauth::test_support::set_base_url")]
    fn init_panics_when_no_override_is_set() {
        let _lock = test_lock();
        clear_base_url();
        let _ = PropelAuth::init(init_options());
    }

    #[test]
    #[should_panic(expected = "must call propelauth::test_support::set_base_url")]
    fn fetch_and_init_panics_when_no_override_is_set() {
        let _lock = test_lock();
        clear_base_url();
        let options = AuthOptions {
            auth_url: AUTH_URL.to_string(),
            api_key: "api-key".to_string(),
        };
        let _ = tokio::runtime::Builder::new_current_thread()
            .enable_all()
            .build()
            .unwrap()
            .block_on(PropelAuth::fetch_and_init(options));
    }

    #[test]
    fn fetch_and_init_requests_the_override_server() {
        let _lock = test_lock();
        let listener = TcpListener::bind("127.0.0.1:0").unwrap();
        let address = listener.local_addr().unwrap();
        let (request_line, received) = mpsc::channel();
        thread::spawn(move || {
            let (mut stream, _) = listener.accept().unwrap();
            let mut buffer = [0u8; 4096];
            let read = stream.read(&mut buffer).unwrap();
            stream
                .write_all(
                    b"HTTP/1.1 401 Unauthorized\r\ncontent-length: 0\r\nconnection: close\r\n\r\n",
                )
                .unwrap();
            let request = String::from_utf8_lossy(&buffer[..read]).to_string();
            let first_line = request.lines().next().unwrap_or_default().to_string();
            request_line.send(first_line).unwrap();
        });
        set_base_url(format!("http://{}", address));

        let options = AuthOptions {
            auth_url: AUTH_URL.to_string(),
            api_key: "api-key".to_string(),
        };
        let result = tokio::runtime::Builder::new_current_thread()
            .enable_all()
            .build()
            .unwrap()
            .block_on(PropelAuth::fetch_and_init(options));
        clear_base_url();

        assert_eq!(
            received
                .recv_timeout(Duration::from_secs(10))
                .expect("the override server received no request"),
            "GET /api/backend/v1/token_verification_metadata HTTP/1.1"
        );
        assert_eq!(result.err(), Some(InitializationError::InvalidApiKey));
    }
}
